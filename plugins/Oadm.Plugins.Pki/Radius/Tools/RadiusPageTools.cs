/// <summary>
/// The page's actions as tools (docs/spec/mcp.md "Page actions", decision 2026-11-15): the Sessions tab, Delete log, Turn on and
/// Turn off, the Server card's Save, and a switch's save and delete, each change a preview (the page's checks, nothing written)
/// and a run with the rights of its page method. A switch's shared secret never passes through an answer: it is entered through
/// the host's secret channel, or generated by the run and handed out once as a file.
/// </summary>
internal static class RadiusPageTools
{
    public const string EmptyLog = "The log is empty.";
    public const string Off = "The 802.1X server is off. Turn it on first.";
    public const string AlreadyOn = "The 802.1X server is on already.";
    public const string AlreadyOff = "The 802.1X server is off already.";
    public const string ChooseSecret = "Use keep, enter or generate.";

    /// <summary>A valid stand-in for a secret the preview does not have yet (the checks of the other fields need one).</summary>
    private const string PreviewSecret = "PreviewOnly2026";

    public static PluginPageTools<RadiusPlugin> Set { get; } = new PluginPageTools<RadiusPlugin>(RadiusTools.Json)
        .Read<NoArgs, SessionsAnswer>(
            new("sessions", "802.1X sessions", "The switch port logins of the 802.1X server in progress and just ended, the newest first: switch, port, device, state and VLAN.")
            {
                Paged = true,
            },
            RadiusMethods.ListSessions,
            SessionsAsync)
        .Read<NoArgs, SwitchesAnswer>(
            new("switches", "802.1X switches", "The switches the 802.1X server answers: id, name, address, site and state. Never a shared secret."),
            RadiusMethods.ListSwitches,
            (plugin, caller, _, _) =>
            {
                if (plugin.Service is not { } service)
                {
                    return Task.FromResult(new SwitchesAnswer(false, []));
                }

                var list = caller.HasAllDevices ? service.ListSwitches() : service.ListSwitches(caller.CoversRoute);
                return Task.FromResult(new SwitchesAnswer(true, [.. list.Switches.Take(RadiusLimits.MaxSwitches).Select(s => new SwitchAnswer(
                    s.Id.ToString(), s.Name, s.Address, s.SiteId?.ToString(), s.SiteName, s.State,
                    s.LastRequestUtc?.ToUniversalTime().ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture)))]));
            })
        .Change<NoArgs, DeletePlan, DeleteResult>(
            new("log_delete", "Delete 802.1X log", "Deletes every entry of the 802.1X server's log.")
            {
                Destructive = true,
            },
            RadiusMethods.DeleteLog,
            (plugin, _, _, _) =>
            {
                var count = Running(plugin).Log.Count;
                return count == 0 ? throw new InvalidOperationException(EmptyLog) : Task.FromResult(new DeletePlan(count));
            },
            (plugin, caller, _, plan, _) =>
            {
                Running(plugin).DeleteLog(caller.UserName);
                return Task.FromResult(new DeleteResult(plan.WillChange));
            })
        .Change<EnableArgs, EnablePlan, EnableResult>(
            new("enable", "Turn the 802.1X server on or off", "Turns the 802.1X server on (needs OADM PRO) or off. Off closes its port: switches get no answer and their ports fall back to what the switch does without RADIUS."),
            ServerSwitchMethods.TurnOn,
            (plugin, _, input, _) => Task.FromResult(CheckSwitch(Switch(plugin), input.Args.Enabled)),
            async (plugin, _, input, _, ct) =>
            {
                var server = Switch(plugin);
                var state = input.Args.Enabled ? await server.TurnOnAsync(ct).ConfigureAwait(false) : await server.TurnOffAsync(ct).ConfigureAwait(false);
                return new EnableResult(state.On, state.Running, state.StatusText);
            })
        .Change<SettingsArgs, SettingsPlan, SettingsResult>(
            new("settings_save", "Save 802.1X server settings", "Changes the interface the 802.1X server listens on, its UDP port and how many log lines it keeps. Fields left out keep their value."),
            RadiusMethods.SaveSettings,
            (plugin, _, input, _) => Task.FromResult(CheckSettings(Running(plugin), input.Args)),
            async (plugin, _, _, plan, ct) =>
            {
                var state = await Fielded(() => Running(plugin).SaveSettingsAsync(plan.Settings, ct)).ConfigureAwait(false);
                return new SettingsResult(state.Settings.Port, state.Settings.ListenOn, state.Settings.LogKept);
            })
        .Change<SwitchArgs, SwitchPlan, SwitchResult>(
            new("switch_save", "Save switch", "Adds a switch the 802.1X server answers, or changes one: name, address, site and shared secret. The secret is entered by you, kept, or generated and handed out once as a file.")
            {
                Secrets = [new PluginToolSecret("shared_secret", "shared secret", RadiusLimits.MaxSecretLength)],
                ReturnsFile = true,
            },
            RadiusMethods.SaveSwitch,
            (plugin, _, input, _) => Task.FromResult(CheckSwitchSave(Running(plugin), input)),
            SaveSwitchAsync)
        .Change<SwitchRefArgs, SwitchDeletePlan, DeleteResult>(
            new("switch_delete", "Delete switch", "Deletes a switch: its open sessions end and the 802.1X server no longer answers it.")
            {
                Destructive = true,
            },
            RadiusMethods.DeleteSwitch,
            (plugin, _, input, _) =>
            {
                var row = FindSwitch(Running(plugin), input.Args.SwitchId);
                return Task.FromResult(new SwitchDeletePlan(row.Name, row.Address, ["Camera ports on this switch can no longer sign in until the switch is added again."]) { Id = row.Id });
            },
            async (plugin, _, _, plan, ct) =>
            {
                await Fielded(async () =>
                {
                    await Running(plugin).DeleteSwitchAsync(plan.Id, ct).ConfigureAwait(false);
                    return true;
                }).ConfigureAwait(false);
                return new DeleteResult(1);
            });

    private static RadiusService Running(RadiusPlugin plugin) => plugin.Service ?? throw new InvalidOperationException(plugin.Server is null ? RadiusTexts.NotRunning : Off);

    private static ServerSwitch<RadiusService> Switch(RadiusPlugin plugin) => plugin.Server ?? throw new InvalidOperationException(RadiusTexts.NotRunning);

    /// <summary>The page method whose audit entry a tool's run writes, as the page's own call does (Turn off for an off run).</summary>
    public static string? AuditDetail(string method, string? payloadJson)
    {
        if (Set.ToolOf(method) is not { } tool || PluginTool.IsPreviewMethod(method))
        {
            return null;
        }

        if (tool.Name == "enable")
        {
            try
            {
                return System.Text.Json.Nodes.JsonNode.Parse(payloadJson ?? "{}")?["enabled"]?.GetValue<bool>() == true ? ServerSwitchMethods.TurnOn : ServerSwitchMethods.TurnOff;
            }
            catch (Exception ex) when (ex is System.Text.Json.JsonException or InvalidOperationException)
            {
                return ServerSwitchMethods.TurnOff;
            }
        }

        return Set.PageMethodOf(method);
    }

    private static EnablePlan CheckSwitch(ServerSwitch<RadiusService> server, bool enabled)
    {
        var state = server.State;
        if (enabled)
        {
            if (!state.ProActive)
            {
                throw new InvalidOperationException(ProLicenseTexts.NeedsPro);
            }

            return state.On ? throw new InvalidOperationException(AlreadyOn)
                : new EnablePlan(true, state.StatusText, ["The server opens UDP 1812 and answers the switches with PKI's 802.1X policies."]);
        }

        return !state.On ? throw new InvalidOperationException(AlreadyOff)
            : new EnablePlan(false, state.StatusText, ["The port closes. Switches get no answer: camera ports that need 802.1X lose the network at their next login."]);
    }

    private static SettingsPlan CheckSettings(RadiusService service, SettingsArgs args)
    {
        var now = service.Settings;
        var settings = now with
        {
            ListenOn = string.IsNullOrWhiteSpace(args.ListenOn) ? now.ListenOn : args.ListenOn.Trim(),
            Port = args.Port ?? now.Port,
            LogKept = args.LogKept ?? now.LogKept,
        };
        if (service.SettingsRefusal(settings) is { } error)
        {
            throw new PluginToolInputException(SettingsField(error.Field), error.Message);
        }

        var warnings = settings.Port != now.Port || !string.Equals(settings.ListenOn, now.ListenOn, StringComparison.Ordinal)
            ? new[] { "Switches set up with the old address or port get no answer until they are set up again." }
            : [];
        return new SettingsPlan(settings.Port, settings.ListenOn, settings.LogKept, warnings) { Settings = settings };
    }

    private static string SettingsField(string field) => field switch
    {
        "listenOn" => "listen_on",
        "logKept" => "log_kept",
        _ => field,
    };

    private static SwitchRow FindSwitch(RadiusService service, string? id) =>
        Guid.TryParse(id, out var switchId) && service.ListSwitches().Switches.FirstOrDefault(s => s.Id == switchId) is { } row
            ? row
            : throw new PluginToolInputException("switch_id", RadiusTexts.SwitchGone);

    private static SwitchPlan CheckSwitchSave(RadiusService service, PluginToolInput<SwitchArgs> input)
    {
        var args = input.Args;
        SwitchRow? existing = args.SwitchId is { Length: > 0 } ? FindSwitch(service, args.SwitchId) : null;
        var secret = args.Secret ?? (existing is null ? "enter" : "keep");
        if (secret is not ("keep" or "enter" or "generate"))
        {
            throw new PluginToolInputException("secret", ChooseSecret);
        }

        Guid? site = existing?.SiteId;
        if (args.SiteId is { } siteText)
        {
            site = siteText.Length == 0 || siteText == "server" ? null
                : Guid.TryParse(siteText, out var siteId) && (siteId == existing?.SiteId || service.HasSite(siteId)) ? siteId
                : throw new PluginToolInputException("site_id", RadiusTexts.SiteGone);
        }

        var request = new SaveSwitchRequest
        {
            Id = existing?.Id,
            Name = args.Name ?? existing?.Name,
            Address = args.Address ?? existing?.Address,
            SiteId = site,
            Secret = secret == "keep" ? null : input.IsRun && secret == "enter" ? input.Secret("shared_secret") : PreviewSecret,
        };
        if (existing is null && service.StoredSwitches.Count >= RadiusLimits.MaxSwitches)
        {
            throw new PluginToolInputException("name", RadiusRules.TooManySwitches);
        }

        if (RadiusRules.Validate(request, service.StoredSwitches.Where(s => s.Id != existing?.Id), existing is null) is { } error)
        {
            throw new PluginToolInputException(error.Field == "secret" ? (secret == "keep" ? "secret" : "secrets.shared_secret") : SwitchField(error.Field), error.Message);
        }

        var warnings = new List<string>();
        if (existing is not null && secret != "keep")
        {
            warnings.Add("Set the new shared secret on the switch too, or it gets no answer.");
        }

        if (secret == "generate")
        {
            warnings.Add("The run hands out the generated secret once, as a file. It is never shown here.");
        }

        return new SwitchPlan(existing is null ? "create" : "change", request.Name!.Trim(), request.Address!.Trim(),
            site is null ? "This server" : site.Value.ToString(), secret, secret == "enter" ? ["shared_secret"] : [], warnings)
        {
            Request = request with { Secret = secret == "keep" ? null : request.Secret },
            SecretChoice = secret,
        };
    }

    private static string SwitchField(string field) => field switch
    {
        "siteId" => "site_id",
        _ => field,
    };

    private static async Task<SwitchResult> SaveSwitchAsync(RadiusPlugin plugin, ICallContext caller, PluginToolInput<SwitchArgs> input, SwitchPlan plan, CancellationToken ct)
    {
        var secret = plan.SecretChoice switch
        {
            "generate" => RadiusService.GenerateSecret(),
            "enter" => input.Secret("shared_secret") ?? throw new PluginToolInputException("secrets.shared_secret", RadiusRules.EnterSecret),
            _ => null,
        };
        var row = await Fielded(() => Running(plugin).SaveSwitchAsync(plan.Request with { Secret = secret }, ct)).ConfigureAwait(false);
        PluginToolFile? file = null;
        if (plan.SecretChoice == "generate")
        {
            var text = string.Create(CultureInfo.InvariantCulture, $"Shared secret of the switch {row.Name} ({row.Address}) for the 802.1X server of OADM:{Environment.NewLine}{secret}{Environment.NewLine}");
            file = plugin.Files.Put(caller, "shared-secret-" + FileNameOf(row.Name) + ".txt", "text/plain", Encoding.UTF8.GetBytes(text), "Shared secret of the switch " + row.Name);
        }

        return new SwitchResult(row.Id.ToString(), row.Name, row.Address, file);
    }

    private static string FileNameOf(string name)
    {
        var safe = new string([.. name.Select(c => char.IsAsciiLetterOrDigit(c) ? c : '-')]).Trim('-');
        return safe.Length == 0 ? "switch" : safe[..Math.Min(safe.Length, 40)];
    }

    /// <summary>The service's field errors (<see cref="RadiusErrors.Field"/>) as the tool's field errors.</summary>
    private static async Task<T> Fielded<T>(Func<Task<T>> call)
    {
        try
        {
            return await call().ConfigureAwait(false);
        }
        catch (ArgumentException ex) when (ex is not PluginToolInputException && ex.ParamName is { Length: > 0 } field)
        {
            var message = ex.Message.Replace($" (Parameter '{field}')", string.Empty, StringComparison.Ordinal);
            throw new PluginToolInputException(field == "secret" ? "secrets.shared_secret" : SettingsField(SwitchField(field)), message);
        }
        catch (KeyNotFoundException ex)
        {
            throw new InvalidOperationException(ex.Message, ex);
        }
    }

    private static async Task<SessionsAnswer> SessionsAsync(RadiusPlugin plugin, ICallContext caller, PluginToolInput<NoArgs> input, CancellationToken ct)
    {
        if (plugin.Service is not { } service)
        {
            return new SessionsAnswer(false, 0, [], null);
        }

        service.Viewers.Seen(caller);
        var all = service.ListSessions(await ViewedSet.OfAsync(caller, ct).ConfigureAwait(false))
            .OrderByDescending(s => s.StartedUtc).ThenBy(s => s.Id).ToList();
        var page = input.Page;
        var offset = int.TryParse(page.After, NumberStyles.None, CultureInfo.InvariantCulture, out var from) ? Math.Clamp(from, 0, all.Count) : 0;
        var (rows, _) = page.Take(all.Skip(offset).Select(RowOf), RadiusTools.Json);
        var end = offset + rows.Count;
        return new SessionsAnswer(true, all.Count, rows, end < all.Count ? end.ToString(CultureInfo.InvariantCulture) : null);
    }

    private static SessionAnswer RowOf(SessionRow row) => new(
        row.StartedUtc.ToUniversalTime().ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture),
        row.SwitchName,
        row.Port,
        row.Mac.Length == 0 ? null : row.Mac,
        row.DeviceId?.ToString(),
        row.DeviceName.Length == 0 ? null : row.DeviceName,
        row.IpAddress.Length == 0 ? null : row.IpAddress,
        row.StateText,
        row.Vlan);

